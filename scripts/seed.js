async function seed() {
  await client.connect()
  console.log('Seeding initial products to Supabase...')
  for (const prod of INITIAL_PRODUCTS) {
    await client.query(
      `INSERT INTO hatoba_products (id, data, updated_at) 
       VALUES ($1, $2, NOW()) 
       ON CONFLICT (id) DO NOTHING`,
      [prod.id, JSON.stringify(prod)]
    )
    console.log('Seeded:', prod.name)
  }
  const count = await client.query('SELECT COUNT(*) FROM hatoba_products')
  console.log(`Total products in DB: ${count.rows[0].count}`)
  await client.end()
}

seed().catch(e => { console.error(e); process.exit(1) })
